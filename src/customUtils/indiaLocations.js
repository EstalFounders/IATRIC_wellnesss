/**
 * Normalises anything the database, the API or a form can hold into the new
 * structured `{ state, city }` shape. Accepts:
 *   - an object already shaped as `{ state, city }` (new documents),
 *   - a legacy "City, State" string,
 *   - a legacy plain-city string ("Mumbai"),
 *   - the old "None" default and empty values (both become empty strings).
 */
export function parseLocation(value) {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return {
      state: String(value.state ?? "").trim(),
      city: String(value.city ?? "").trim(),
    };
  }

  const text = typeof value === "string" ? value.trim() : "";
  if (!text || text === "None") return { state: "", city: "" };

  const separator = text.lastIndexOf(", ");
  if (separator === -1) return { state: "", city: text };
  return {
    state: text.slice(separator + 2).trim(),
    city: text.slice(0, separator).trim(),
  };
}

/**
 * Human-readable "City, State" label (falls back to whichever part is present).
 * Used wherever the stored location is shown as a single line.
 */
export function formatLocation(value) {
  const { state, city } = parseLocation(value);
  if (city && state) return `${city}, ${state}`;
  return city || state;
}
